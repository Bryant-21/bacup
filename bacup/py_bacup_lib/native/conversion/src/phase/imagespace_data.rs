use std::collections::BTreeMap;
use std::io::Write;

use esp_authoring_core::plugin_runtime::{ParsedSubrecord, effective_subrecords_for_record};

use crate::ids::{FormKey, SigCode};
use crate::phase::{Phase, PhaseCtx, PhaseError, PhaseReport};
use crate::session::open_session;
use crate::target_normalize::fo76_imgs_is_physical_exterior;
use crate::translator::Game;

// FO4's HNAM has no slot for these, so FO4CS reads them from this file instead.
const SIDECAR_DIR: &str = "F4SE/Plugins/FO4CS";
const SIDECAR_FILE: &str = "ImagespaceData.ini";
const ENAM_EXPOSURE_MAX: usize = 4;
const ENAM_EXPOSURE_MIN: usize = 5;
const ENAM_SUN_ILLUMINANCE: usize = 6;
const ENAM_SKY_ILLUMINANCE: usize = 7;
const ENAM_FOG_SCALE: usize = 9;
const DEFAULT_XNAM: [f32; 5] = [0.0, 0.0, 16.0, 0.008, 100.0];

pub struct ImagespaceDataPhase;

#[derive(Debug, Clone, PartialEq)]
struct ImagespaceRow {
    fog_scale: f32,
    sky_illuminance: f32,
    sun_illuminance: f32,
    exposure_mode: u32,
    /// XNAM: exposure value, compensation, aperture, shutter seconds, ISO.
    exposure: [f32; 5],
    /// The source EV100 auto-exposure limits (max, min), present when the
    /// HNAM adapter already wrote them to FO4 as linear exposure; FO4CS must
    /// not convert those again.
    source_exposure_ev: Option<[f32; 2]>,
}

fn floats(field: &ParsedSubrecord) -> Vec<f32> {
    field
        .data
        .chunks_exact(4)
        .map(|chunk| f32::from_le_bytes(chunk.try_into().unwrap()))
        .collect()
}

fn imagespace_row(fields: &[ParsedSubrecord]) -> Option<ImagespaceRow> {
    let field = |signature: &str| fields.iter().find(|field| field.signature == signature);
    // Older records keep the same HDR block in FNAM.
    let enam = floats(field("ENAM").or_else(|| field("FNAM"))?);
    if enam.len() <= ENAM_FOG_SCALE {
        return None;
    }
    let exposure = field("XNAM")
        .map(floats)
        .and_then(|values| <[f32; 5]>::try_from(values).ok())
        .unwrap_or(DEFAULT_XNAM);
    let exposure_mode = field("YNAM")
        .and_then(|field| field.data.get(..4))
        .map(|bytes| u32::from_le_bytes(bytes.try_into().unwrap()))
        .unwrap_or(0);
    let row = ImagespaceRow {
        fog_scale: enam[ENAM_FOG_SCALE],
        sky_illuminance: enam[ENAM_SKY_ILLUMINANCE],
        sun_illuminance: enam[ENAM_SUN_ILLUMINANCE],
        exposure_mode,
        exposure,
        source_exposure_ev: fo76_imgs_is_physical_exterior(enam[ENAM_SUN_ILLUMINANCE])
            .then(|| [enam[ENAM_EXPOSURE_MAX], enam[ENAM_EXPOSURE_MIN]])
            .filter(|window| window.iter().all(|value| value.is_finite())),
    };
    let values = [row.fog_scale, row.sky_illuminance, row.sun_illuminance];
    values
        .iter()
        .chain(row.exposure.iter())
        .all(|value| value.is_finite())
        .then_some(row)
}

fn render_ini(rows: &BTreeMap<(String, u32), ImagespaceRow>) -> String {
    let mut out = String::from(
        "; Generated by BACUP. Source image-space values FO4's IMGS cannot hold.\n\
         ; Plugin|ObjectID = fogScale, skyIlluminance, sunIlluminance, exposureMode, \
         exposureValue, compensationEv, aperture, shutterSeconds, iso\
         [, sourceExposureMaxEv, sourceExposureMinEv]\n\
         ; The source EV pair is present when the IMGS HNAM already holds it as FO4 exposure.\n\
         [ImageSpaces]\n",
    );
    for ((plugin, local), row) in rows {
        let [ev, compensation, aperture, shutter, iso] = row.exposure;
        out.push_str(&format!(
            "{plugin}|{local:06X} = {}, {}, {}, {}, {ev}, {compensation}, {aperture}, {shutter}, {iso}",
            row.fog_scale, row.sky_illuminance, row.sun_illuminance, row.exposure_mode
        ));
        if let Some([max_ev, min_ev]) = row.source_exposure_ev {
            out.push_str(&format!(", {max_ev}, {min_ev}"));
        }
        out.push('\n');
    }
    out
}

fn source_key(raw: u32, masters: &[String], plugin: &str) -> Result<(String, u32), PhaseError> {
    let index = (raw >> 24) as usize;
    let owner = if index == masters.len() || index == 0xff {
        plugin
    } else {
        masters
            .get(index)
            .map(String::as_str)
            .ok_or_else(|| PhaseError::Internal(format!("invalid IMGS FormID {raw:08X}")))?
    };
    Ok((owner.into(), raw & 0xffffff))
}

impl Phase for ImagespaceDataPhase {
    fn name(&self) -> &'static str {
        "emit_imagespace_data"
    }

    fn run(&self, ctx: &mut PhaseCtx<'_>) -> Result<PhaseReport, PhaseError> {
        if ctx.run.source != Game::Fo76 || ctx.run.target != Game::Fo4 {
            return Ok(PhaseReport::default());
        }
        if ctx.mod_path.as_os_str().is_empty() {
            return Err(PhaseError::BadParams(
                "image-space data requires mod_path".into(),
            ));
        }
        let mut session = open_session(ctx.run.target_handle_id, Some(ctx.run.source_handle_id))
            .map_err(|e| PhaseError::Internal(e.to_string()))?;
        let (masters, plugin) = session
            .handle_load_order(ctx.run.source_handle_id)
            .map(|(masters, plugin)| (masters.to_vec(), plugin.to_string()))
            .map_err(|e| PhaseError::Internal(e.to_string()))?;
        let scan = session
            .handle_raw_scan(ctx.run.source_handle_id)
            .map_err(|e| PhaseError::Internal(e.to_string()))?;
        let mut source_rows = Vec::new();
        for raw in scan.raw_form_ids_of_sig(SigCode::from_str("IMGS").unwrap()) {
            ctx.check_cancel()?;
            let row = scan
                .with_record(raw, |record| {
                    if record.flags & 0x20 != 0 {
                        return None;
                    }
                    imagespace_row(&effective_subrecords_for_record(record))
                })
                .flatten();
            if let Some(row) = row {
                source_rows.push((raw, row));
            }
        }
        drop(scan);
        let mut rows = BTreeMap::new();
        let mut skipped = 0;
        for (raw, row) in source_rows {
            let (owner, local) = source_key(raw, &masters, &plugin)?;
            let source = FormKey {
                local,
                plugin: ctx.run.interner.intern(&owner),
            };
            let Some(target) = ctx
                .run
                .mapper_state
                .as_ref()
                .and_then(|map| map.source_to_target.get(&source))
            else {
                skipped += 1;
                continue;
            };
            let owner = ctx
                .run
                .interner
                .resolve(target.plugin)
                .unwrap_or("")
                .to_string();
            rows.insert((owner, target.local), row);
        }
        let directory = ctx.mod_path.join(SIDECAR_DIR);
        std::fs::create_dir_all(&directory).map_err(|e| PhaseError::Internal(e.to_string()))?;
        let mut pending = tempfile::NamedTempFile::new_in(&directory)
            .map_err(|e| PhaseError::Internal(e.to_string()))?;
        pending
            .write_all(render_ini(&rows).as_bytes())
            .map_err(|e| PhaseError::Internal(e.to_string()))?;
        pending
            .persist(directory.join(SIDECAR_FILE))
            .map_err(|e| PhaseError::Internal(e.to_string()))?;
        Ok(PhaseReport {
            assets_written: 1,
            warnings: skipped,
            ..PhaseReport::default()
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn field(signature: &str, values: &[f32]) -> ParsedSubrecord {
        ParsedSubrecord {
            signature: signature.into(),
            data: values
                .iter()
                .flat_map(|value| value.to_le_bytes())
                .collect::<Vec<u8>>()
                .into(),
            semantic_type: None,
        }
    }

    fn mall_enam() -> ParsedSubrecord {
        field(
            "ENAM",
            &[8.0, 0.02, 0.5, 0.0, 4.5, 2.5, 0.0, 100.0, 0.18, 0.3, 11.2, 2.0, 1.0],
        )
    }

    #[test]
    fn row_reads_fog_illuminance_and_exposure() {
        let mut ynam = field("YNAM", &[]);
        ynam.data = 1_u32.to_le_bytes().to_vec().into();
        let row = imagespace_row(&[
            mall_enam(),
            field("XNAM", &[4.0, 0.5, 16.0, 0.008, 100.0]),
            ynam,
        ])
        .unwrap();
        assert_eq!(
            row,
            ImagespaceRow {
                fog_scale: 0.3,
                sky_illuminance: 100.0,
                sun_illuminance: 0.0,
                exposure_mode: 1,
                exposure: [4.0, 0.5, 16.0, 0.008, 100.0],
                source_exposure_ev: None,
            }
        );
    }

    #[test]
    fn row_defaults_missing_exposure_and_rejects_short_or_bad_enam() {
        let row = imagespace_row(&[mall_enam()]).unwrap();
        assert_eq!(row.exposure_mode, 0);
        assert_eq!(row.exposure, DEFAULT_XNAM);

        assert_eq!(imagespace_row(&[field("ENAM", &[1.0; 9])]), None);
        assert_eq!(imagespace_row(&[]), None);
        let mut bad = [1.0_f32; 13];
        bad[ENAM_FOG_SCALE] = f32::NAN;
        assert_eq!(imagespace_row(&[field("ENAM", &bad)]), None);
    }

    #[test]
    fn row_reads_the_hdr_block_from_fnam_on_older_records() {
        let row = imagespace_row(&[field(
            "FNAM",
            &[10.0, 0.02, 0.5, 0.0, 4.0, 3.0, 1.0, 100.0, 0.18, 1.0, 11.2],
        )])
        .unwrap();
        assert_eq!(row.fog_scale, 1.0);
        assert_eq!(row.sky_illuminance, 100.0);
        assert_eq!(row.sun_illuminance, 1.0);
    }

    #[test]
    fn ini_lists_rows_by_plugin_and_object_id() {
        let mall = imagespace_row(&[mall_enam(), field("XNAM", &[4.0, 0.0, 16.0, 0.008, 100.0])])
            .unwrap();
        let rows = BTreeMap::from([(("SeventySix.esm".to_string(), 0x52ED9A), mall)]);
        let ini = render_ini(&rows);
        assert!(ini.contains("[ImageSpaces]\n"));
        assert!(ini.ends_with("SeventySix.esm|52ED9A = 0.3, 100, 0, 0, 4, 0, 16, 0.008, 100\n"));
    }

    #[test]
    fn weather_rows_carry_the_source_ev_window_the_hnam_converted() {
        let clear = imagespace_row(&[field(
            "ENAM",
            &[2.0, 0.02, 0.5, 0.0, 6.0, 2.0, 300.0, 100.0, 0.18, 1.0, 11.2, 1.0, 1.0],
        )])
        .unwrap();
        assert_eq!(clear.source_exposure_ev, Some([6.0, 2.0]));
        let rows = BTreeMap::from([(("SeventySix.esm".to_string(), 0x4398A1), clear)]);
        assert!(render_ini(&rows).ends_with(
            "SeventySix.esm|4398A1 = 1, 100, 300, 0, 0, 0, 16, 0.008, 100, 6, 2\n"
        ));
    }

    #[test]
    fn source_keys_follow_master_ownership() {
        let masters = vec!["SeventySix.esm".to_string()];
        assert_eq!(
            source_key(0x0052ED9A, &masters, "Patch.esp").unwrap(),
            ("SeventySix.esm".into(), 0x52ED9A)
        );
        assert_eq!(
            source_key(0x01000800, &masters, "Patch.esp").unwrap(),
            ("Patch.esp".into(), 0x800)
        );
        assert!(source_key(0x05000800, &masters, "Patch.esp").is_err());
    }
}
