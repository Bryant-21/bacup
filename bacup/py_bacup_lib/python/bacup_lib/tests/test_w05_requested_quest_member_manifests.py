def _expected_members(spec: str) -> list[str]:
    members = []
    for token in spec.split(","):
        stage, _, item = token.partition(":")
        members.append(
            f"fragment_stage_{int(stage):04d}_item_{int(item or '0'):02d}"
        )
    return members


def _actual_members(source: str) -> list[tuple[str, str, int, int]]:
    return [
        (kind, name, start, end)
        for kind, name, start, end in _iter_top_level_papyrus_members(
            source.splitlines()
        )
        if kind in {"function", "event"}
    ]


def _has_executable_body(lines: list[str], start: int, end: int) -> bool:
    return any(
        line.strip() and not line.lstrip().startswith(";")
        for line in lines[start + 1 : end]
    )


def test_requested_22_quest_patches_have_exact_reconciled_member_sets():
    assert len(REQUESTED_QUEST_MEMBERS) == 22
    assert len(REQUESTED_QUEST_MEMBER_COUNTS) == 22
    for script_name, spec in REQUESTED_QUEST_MEMBERS.items():
        patch = _script_patch_source(script_name)
        assert patch is not None, script_name
        expected = _expected_members(spec)
        assert len(expected) == len(set(expected)), script_name
        assert len(expected) == REQUESTED_QUEST_MEMBER_COUNTS[script_name[-8:]]

        lines = patch.splitlines()
        actual = _actual_members(patch)
        expected_members = {
            *(('function', name) for name in expected),
            *REQUESTED_QUEST_EXTRA_MEMBERS.get(script_name, set()),
        }
        actual_members = {
            (kind, name) for kind, name, _start, _end in actual
        }
        assert actual_members == expected_members, script_name
        actual_names = [name for _kind, name, _start, _end in actual]
        assert len(actual_names) == len(set(actual_names)), script_name

        hollow = [
            name
            for _kind, name, start, end in actual
            if not _has_executable_body(lines, start, end)
        ]
        assert hollow == [], f"{script_name}: hollow members {hollow}"
