"""Hollow-script ledger: merge triage shards into status.csv and report what cannot be patched.

    uv run --no-sync python bacup/scripts/stub_ledger.py merge <shard.csv>...
    uv run --no-sync python bacup/scripts/stub_ledger.py report [--write]
"""

from __future__ import annotations

import argparse
import collections
import csv
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LEDGER_DIR = ROOT / "bacup" / "docs" / "stub_restoration"
STATUS = LEDGER_DIR / "status.csv"
REPORT = LEDGER_DIR / "UNPATCHABLE.md"
FIELDS = [
    "relative_path", "script_name", "system_chain", "effect_bucket", "disposition_initial",
    "shard", "wave", "terminal_state", "evidence", "notes",
]
TERMINAL = {"patched", "non-defect", "unsupported-online", "evidence-blocked", "record-dependency"}
ALIASES = {"insufficient-evidence": "evidence-blocked"}
UNPATCHABLE_ORDER = ["record-dependency", "evidence-blocked", "unsupported-online", "non-defect"]
STATE_MEANING = {
    "record-dependency": "Fixable only after a converter/record change; the script alone cannot work.",
    "evidence-blocked": "No defensible behaviour could be recovered from records, Server76 or analogs.",
    "unsupported-online": "Behaviour depends on FO76 online services (instancing, matchmaking, server).",
    "non-defect": "Nothing to patch: unbound, cut/debug content, empty by design, or behaviour supplied elsewhere.",
}


def _key(path: str) -> str:
    return path.strip().replace("\\", "/").lower()


def _read(path: Path) -> list[dict[str, str]]:
    with open(path, encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def _write_status(rows: list[dict[str, str]]) -> None:
    fd, tmp = tempfile.mkstemp(dir=LEDGER_DIR, prefix="status.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", newline="", encoding="utf-8") as fh:
            writer = csv.DictWriter(fh, fieldnames=FIELDS, extrasaction="ignore")
            writer.writeheader()
            writer.writerows(rows)
        os.replace(tmp, STATUS)
    except BaseException:
        os.unlink(tmp)
        raise


def merge(shards: list[Path], only_new: bool = False) -> int:
    rows = _read(STATUS)
    index = {_key(r["relative_path"]): r for r in rows}
    added = updated = 0
    for shard in shards:
        for incoming in _read(shard):
            state = ALIASES.get(incoming["terminal_state"].strip(), incoming["terminal_state"].strip())
            if state not in TERMINAL:
                print(f"ERROR: {shard.name}: {incoming['relative_path']}: bad state {state!r}", file=sys.stderr)
                return 1
            incoming = {f: (incoming.get(f) or "").strip() for f in FIELDS} | {"terminal_state": state}
            existing = index.get(_key(incoming["relative_path"]))
            if existing is None:
                rows.append(incoming)
                index[_key(incoming["relative_path"])] = incoming
                added += 1
            elif not only_new:
                existing.update(incoming)
                updated += 1
    _write_status(rows)
    print(f"merged {len(shards)} shard(s): {added} added, {updated} updated, {len(rows)} rows")
    if only_new:
        print("  (--only-new: existing rows kept)")
    return 0


def report(write: bool) -> int:
    rows = _read(STATUS)
    states = collections.Counter(r["terminal_state"] for r in rows)
    print(f"{len(rows)} ledger rows")
    for state, count in states.most_common():
        print(f"  {count:6}  {state}")
    if not write:
        return 0

    lines = [
        "# Scripts we cannot patch",
        "",
        "Generated by `bacup/scripts/stub_ledger.py report --write` from `status.csv`. Do not edit by hand.",
        "",
        "| State | Count | Meaning |",
        "|---|---:|---|",
    ]
    lines += [f"| `{s}` | {states.get(s, 0)} | {STATE_MEANING[s]} |" for s in UNPATCHABLE_ORDER]
    lines += [f"| `patched` | {states.get('patched', 0)} | Repaired (source only; see status.csv for runtime gates). |", ""]
    for state in UNPATCHABLE_ORDER:
        chosen = sorted((r for r in rows if r["terminal_state"] == state),
                        key=lambda r: (r["system_chain"].lower(), r["relative_path"].lower()))
        if not chosen:
            continue
        by_system = collections.Counter(r["system_chain"] or "(unassigned)" for r in chosen)
        lines += [f"## `{state}` ({len(chosen)})", "", STATE_MEANING[state], "", "| System | Count |", "|---|---:|"]
        lines += [f"| {system} | {count} |" for system, count in by_system.most_common()]
        lines += ["", "<details>", f"<summary>All {len(chosen)} scripts</summary>", "",
                  "| Script | System | Evidence |", "|---|---|---|"]
        for r in chosen:
            evidence = r["evidence"].replace("|", "\\|").replace("\n", " ")
            lines.append(f"| `{r['relative_path']}` | {r['system_chain']} | {evidence} |")
        lines += ["", "</details>", ""]
    REPORT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {REPORT.relative_to(ROOT)}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("merge", help="add or update status.csv rows from triage shard CSVs")
    m.add_argument("shards", nargs="+", type=Path)
    m.add_argument("--only-new", action="store_true", help="add missing rows; never overwrite existing ones")
    r = sub.add_parser("report", help="summarise status.csv; --write regenerates UNPATCHABLE.md")
    r.add_argument("--write", action="store_true")
    args = ap.parse_args()
    return merge(args.shards, args.only_new) if args.cmd == "merge" else report(args.write)


if __name__ == "__main__":
    sys.exit(main())
