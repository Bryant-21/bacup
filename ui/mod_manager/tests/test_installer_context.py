def test_capture_truthful_states_forced_plugins_winners_and_read_only(context_fixture):
    library, profile_id, game, _, mod, overwrite = context_fixture
    watched = [path for root in (game, mod, overwrite) for path in root.rglob("*") if path.is_file()]
    before = {path: path.read_bytes() for path in watched}
    profile = library.profile_snapshot(profile_id)
    context, states = installer_context.capture(library, profile_id, script("Absent.esp", "textures/missing.dds"))
    assert states["fallout4.esm"] == states["dlcrobot.esm"] == states["ccfixture.esl"] == "Active"
    assert states["addon.esp"] == "Active" and states["inactive.esp"] == "Inactive"
    assert states["absent.esp"] == "Missing"
    assert states["textures/missing.dds"] == "Missing"  # Complete FO4 archive inventory now establishes absence.
    assert "hidden.esp" not in states and "ghost.esp.ghost" not in states
    assert "secret/asset.txt" not in states
    assert context.file_count == 6 and any(plugin[4] for plugin in context.plugins)
    installer_context.validate(library, context)
    assert {path: path.read_bytes() for path in watched} == before
    assert library.profile_snapshot(profile_id) == profile


@pytest.mark.parametrize("mutation", [
    "enable", "group", "tags", "notes", "plugin_activation", "profile_name", "profile_delete", "game_config",
    "source_config", "game_add", "game_remove", "game_change", "source_add", "source_remove", "source_change",
    "overwrite_add", "overwrite_remove", "overwrite_change", "source_unavailable", "ccc_change", "ccc_remove",
])
def test_validate_rejects_stale_selected_context(context_fixture, tmp_path, mutation):
    library, profile_id, game, mod_id, mod, overwrite = context_fixture
    context, _ = installer_context.capture(library, profile_id, script("Absent.esp"))
    if mutation in {"enable", "group", "tags", "notes"}:
        library.customize(profile_id, mod_id, **{"enabled" if mutation == "enable" else mutation: False if mutation == "enable" else "changed"})
    elif mutation == "plugin_activation":
        change_files(library, profile_id, **{"plugins.txt": "Inactive.esp\n"})
    elif mutation == "profile_name":
        rename(library, profile_id, "Changed generated profile")
    elif mutation == "profile_delete":
        library.delete_profile(profile_id)
    elif mutation == "game_config":
        other = game_fixture(tmp_path / "other")
        with library._db() as db:
            row = db.execute("SELECT id,configuration FROM instances").fetchone()
            configuration = json.loads(row[1])
            configuration["game"]["gamepath"] = str(other)
            db.execute("UPDATE instances SET configuration=? WHERE id=?", (json.dumps(configuration), row[0]))
    elif mutation == "source_config":
        other = tmp_path / "another generated provider"
        other.mkdir()
        with library._db() as db:
            db.execute("UPDATE mods SET source=? WHERE id=?", (str(other), mod_id))
    elif mutation == "source_unavailable":
        mod.rename(mod.with_name(mod.name + "-unavailable"))
    elif mutation.startswith("ccc_"):
        if mutation == "ccc_remove":
            (game / "Fallout4.ccc").unlink()
        else:
            (game / "Fallout4.ccc").write_text("CCFixture.esl\nAddon.esp\n")
    else:
        scope, operation = mutation.split("_")
        root = {"game": game / "Data", "source": mod, "overwrite": overwrite}[scope]
        if operation == "add":
            (root / "new-condition-asset.txt").write_bytes(b"generated newly added")
        else:
            target = root / ("Inactive.esp" if scope == "game" else "Addon.esp" if scope == "source" else "textures/shared.txt")
            if operation == "remove":
                target.unlink()
            else:
                target.write_bytes(b"changed generated file with distinct size")
    with pytest.raises(ManagerError):
        installer_context.validate(library, context)


