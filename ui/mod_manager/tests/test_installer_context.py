@pytest.mark.parametrize("mutation", ["organization", "asset_change", "asset_add", "ccc"])
def test_capture_rejects_mutation_during_scan(context_fixture, monkeypatch, mutation):
    library, profile_id, game, mod_id, _, _ = context_fixture
    from creation_lib.mod_manager import conflicts
    original = conflicts.build_index
    def changed(*args, **kwargs):
        index = original(*args, **kwargs)
        if mutation == "organization":
            library.customize(profile_id, mod_id, group="Changed during scan")
        elif mutation == "asset_change":
            (game / "Data/Inactive.esp").write_bytes(b"changed after first inventory")
        elif mutation == "asset_add":
            (game / "Data/new-condition-asset.txt").write_bytes(b"generated during scan")
        else:
            (game / "Fallout4.ccc").write_text("CCFixture.esl\nAddon.esp\n")
        return index
    monkeypatch.setattr(conflicts, "build_index", changed)
    with pytest.raises(ManagerError, match="changed"):
        installer_context.capture(library, profile_id, script())


