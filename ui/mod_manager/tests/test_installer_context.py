@pytest.mark.parametrize("operation", ["capture", "validate"])
def test_pre_cancel_propagates_without_false_stale_error(context_fixture, operation):
    library, profile_id, *_ = context_fixture
    context, _ = installer_context.capture(library, profile_id, script())
    cancel = threading.Event()
    cancel.set()
    with pytest.raises(Cancelled):
        if operation == "capture":
            installer_context.capture(library, profile_id, script(), cancel)
        else:
            installer_context.validate(library, context, cancel)


