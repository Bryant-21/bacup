def script(*names):
    dependencies = "".join(f'<fileDependency file="{name}" state="Missing"/>' for name in names)
    return Fomod(f'<config><moduleName>Generated context fixture</moduleName><moduleDependencies>{dependencies}</moduleDependencies></config>'.encode())


def test_cached_fingerprint_pass_rechecks_parent_identity_after_directory_swap(tmp_path, monkeypatch):
    folder = tmp_path / "provider"
    folder.mkdir()
    path = folder / "fixture.txt"
    path.write_bytes(b"original generated bytes")
    info = path.stat()
    winners = {"fixture.txt": ("fixture.txt", str(path), info.st_size, info.st_mtime_ns)}
    original_lstat, swapped = Path.lstat, False
    def replaced(target):
        nonlocal swapped
        result = original_lstat(target)
        if target == path and not swapped:
            swapped = True
            folder.rename(tmp_path / "retained-original")
            folder.mkdir()
            path.write_bytes(b"different generated data")
            os.utime(path, ns=(info.st_atime_ns, info.st_mtime_ns))
        return result
    monkeypatch.setattr(Path, "lstat", replaced)
    with pytest.raises(ManagerError, match="directory changed"):
        installer_context._verify_winners(winners, None, None)
    assert tmp_path.joinpath("retained-original/fixture.txt").read_bytes() == b"original generated bytes"


def change_files(library, profile_id, **changes):
    with library._db() as db:
        files = json.loads(db.execute("SELECT files FROM profiles WHERE id=?", (profile_id,)).fetchone()[0])
        files.update(changes)
        db.execute("UPDATE profiles SET files=? WHERE id=?", (json.dumps(files), profile_id))


def install_fixture(library, profile_id, tmp_path):
    folder = tmp_path / "generated package"
    (folder / "textures").mkdir(parents=True)
    (folder / "textures/shared.txt").write_bytes(b"generated mod winner")
    (folder / "Addon.esp").write_bytes(b"generated plugin placeholder; no header parsing")
    (folder / "Hidden.esp.mohidden").write_bytes(b"generated hidden")
    (folder / "Ghost.esp.ghost").write_bytes(b"generated ghost")
    package = Package(folder)
    try:
        mod_id = library.install(package, package.plain_plan(), "Generated Mod", profile_id)
    finally:
        package.close()
    return mod_id, Path(library.rows(profile_id)[0].source)


